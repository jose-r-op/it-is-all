-- 1) Tabla principal (manejada manualmente desde el Table Editor)
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  price numeric(12, 2) not null check (price >= 0),
  category text not null default 'GENERAL',
  sizes text not null default 'S, M, L',      -- Texto separado por comas: "S, M, L, XL" o "Única"
  image_url text not null,
  available boolean not null default true,     -- Ponlo en false cuando la prenda se venda / agote
  featured boolean not null default false,     -- true = aparece primero en el catálogo
  badge text,                                  -- ej. 'DROP EXCLUSIVO', 'MÁS VENDIDO'
  tagline text,                                -- ej. 'Heavyweight 480GSM / Algodón perchado'
  symbol text default '✦',                     -- ej. '✦', '☩', '◈', '✝', '▲', '✕'
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2) Índice parcial para acelerar el listado de prendas disponibles
create index if not exists products_available_created_idx
  on public.products (created_at desc)
  where available = true;

-- 3) Row Level Security: la web (anon) solo puede LEER prendas disponibles.
alter table public.products enable row level security;

drop policy if exists "Permitir lectura pública de productos disponibles" on public.products;
create policy "Permitir lectura pública de productos disponibles"
  on public.products for select
  to anon, authenticated
  using (available = true);

-- 4) Bucket público para fotos de las prendas (Storage > products)
insert into storage.buckets (id, name, public)
values ('products', 'products', true)
on conflict (id) do nothing;

drop policy if exists "Lectura pública de imágenes de productos" on storage.objects;
create policy "Lectura pública de imágenes de productos"
  on storage.objects for select
  to anon, authenticated
  using (bucket_id = 'products');

